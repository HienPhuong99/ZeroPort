// Bridge between the sandboxed UI and electron/main.js. Its presence (`window.zp`) is how the UI knows it can host.
const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('zp', {
  platform: process.platform,
  cfgGet: () => ipcRenderer.invoke('cfg:get'),
  cfgSet: (cfg) => ipcRenderer.invoke('cfg:set', cfg),
  hostname: () => ipcRenderer.invoke('hostname'),
  input: (m) => ipcRenderer.send('input', m),
  sessionCount: (n) => ipcRenderer.send('sessions', n),
  displays: () => ipcRenderer.invoke('displays'),
  selectDisplay: (id) => ipcRenderer.invoke('display:select', id),
  onLocked: (fn) => ipcRenderer.on('locked', (_e, locked) => fn(locked)),
  clipRead: () => ipcRenderer.invoke('clip:read'),
  clipWrite: (text) => ipcRenderer.send('clip:write', text),
  fileOpen: (name) => ipcRenderer.invoke('file:open', name),
  fileWrite: (id, chunk) => ipcRenderer.invoke('file:write', id, chunk),
  fileClose: (id, ok) => ipcRenderer.invoke('file:close', id, ok),
  filePick: () => ipcRenderer.invoke('file:pick'),
  fileRead: (id, offset, length) => ipcRenderer.invoke('file:read', id, offset, length),
  fileDone: (id) => ipcRenderer.invoke('file:done', id),
  power: (cmd) => ipcRenderer.invoke('sys:power', cmd),
  sysInfo: () => ipcRenderer.invoke('sys:info'),
  kill: (pid) => ipcRenderer.invoke('sys:kill', pid),
  privacy: (on) => ipcRenderer.invoke('sys:privacy', on),
  macs: () => ipcRenderer.invoke('sys:macs'),
  wake: (list) => ipcRenderer.invoke('sys:wake', list),
  termOpen: (id) => ipcRenderer.invoke('term:open', id),
  termWrite: (id, s) => ipcRenderer.send('term:write', id, s),
  termClose: (id) => ipcRenderer.send('term:close', id),
  onTerm: (fn) => ipcRenderer.on('term', (_e, id, kind, data) => fn(id, kind, data)),
  annotate: (msg) => ipcRenderer.invoke('sys:annotate', msg),
  tcpHostOpen: (sid, id, port) => ipcRenderer.send('tcp:host:open', sid, id, port),
  tcpHostSend: (sid, id, buf) => ipcRenderer.send('tcp:host:send', sid, id, buf),
  tcpHostDrop: (sid, id) => ipcRenderer.send('tcp:host:drop', sid, id),
  onTcpHost: (fn) => { const h = (_e, sid, kind, id, data) => fn(sid, kind, id, data); ipcRenderer.on('tcp:host', h); return () => ipcRenderer.removeListener('tcp:host', h) },
  tcpListen: (sid, lp, rp) => ipcRenderer.invoke('tcp:ctl:listen', sid, lp, rp),
  tcpUnlisten: (sid, lp) => ipcRenderer.send('tcp:ctl:unlisten', sid, lp),
  tcpCtlSend: (sid, id, buf) => ipcRenderer.send('tcp:ctl:send', sid, id, buf),
  tcpCtlDrop: (sid, id) => ipcRenderer.send('tcp:ctl:drop', sid, id),
  onTcpCtl: (fn) => { const h = (_e, sid, kind, id, data) => fn(sid, kind, id, data); ipcRenderer.on('tcp:ctl', h); return () => ipcRenderer.removeListener('tcp:ctl', h) },
  tcpCloseAll: (sid, connsOnly) => ipcRenderer.send('tcp:closeAll', sid, connsOnly),
  tcpAck: (sid, id) => ipcRenderer.send('tcp:ack', sid, id),
  notify: (body) => ipcRenderer.send('notify', body),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  autostartGet:() => ipcRenderer.invoke('autostart:get'),
  autostartSet: (on) => ipcRenderer.invoke('autostart:set', on),
})
